package shop.notification;

/**
 * Клас {@code Notification} — роль {@code Product} у шаблоні
 * <b>Factory Method</b>.
 * <p>
 * Спільний інтерфейс для всіх видів сповіщень, якими система
 * інформує покупця про події в кошику/замовленні (підтвердження
 * оформлення, зміна статусу доставки, нагадування про покинутий
 * кошик тощо). Клієнтський код ({@link NotificationCreator}) працює
 * лише з цим інтерфейсом і не знає, який конкретний канал доставки
 * повідомлення буде використано.
 */
public interface Notification {

    /**
     * Надсилає повідомлення отримувачу певним каналом.
     *
     * @param recipient адреса/ідентифікатор отримувача (email, номер
     *                  телефону, ідентифікатор пристрою для push)
     * @param message   текст повідомлення
     */
    void send(String recipient, String message);
}
