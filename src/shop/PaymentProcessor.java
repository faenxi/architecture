package shop;

/**
 * Стабільний інтерфейс обробки оплати.
 * <p>
 * Реалізує принцип <b>Protected Variations</b>: спосіб оплати — це
 * "точка нестійкості" (сьогодні картка, завтра — новий платіжний
 * провайдер), тому вона ізольована за стабільним інтерфейсом.
 * Класи {@link Order} та {@link CartController} працюють лише з цим
 * інтерфейсом і не залежать від конкретної реалізації.
 * <p>
 * Реалізує <b>Polymorphism</b>: різні реалізації ({@link CardPayment},
 * {@link CashOnDeliveryPayment}, {@link PayPalPayment}) по-різному
 * виконують {@link #pay(double)}, а виклик — однаковий.
 * <p>
 * Забезпечує також <b>Low Coupling</b>: Order/Cart не залежать від
 * конкретних платіжних бібліотек чи API, а лише від цього інтерфейсу.
 */
public interface PaymentProcessor {

    /**
     * Виконує оплату вказаної суми.
     * Це бізнес-логіка інтеграції з реальним платіжним сервісом,
     * тому в конкретних реалізаціях метод є заглушкою.
     *
     * @param amount сума до сплати
     * @return true, якщо оплата успішна
     */
    boolean pay(double amount);

    /** @return людську назву способу оплати (для чеків, логів) */
    String getMethodName();
}
