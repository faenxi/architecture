package shop.checkout;

/**
 * {@code AbstractFactory} у шаблоні <b>Abstract Factory</b>.
 * <p>
 * Оголошує створення пов'язаного сімейства об'єктів — процесора
 * оплати та служби доставки, — які мають використовуватись РАЗОМ,
 * щоб гарантувати їхню сумісність (наприклад, валюта платежу та
 * зона покриття служби доставки повинні відповідати одна одній).
 * <p>
 * Проблема, яку вирішує шаблон: без Abstract Factory клієнтський код
 * ({@link CheckoutService}) мусив би сам обирати сумісні комбінації
 * {@code PaymentProcessor} + {@code ShippingProvider} і легко міг би
 * випадково поєднати, наприклад, міжнародний платіж із локальною
 * доставкою. Конкретна фабрика гарантує узгодженість родини
 * об'єктів "з коробки" й дозволяє замінити всю родину одним рядком
 * коду (підміна фабрики), не чіпаючи клієнтський код.
 */
public interface CheckoutServiceFactory {

    /**
     * Створює процесор оплати, сумісний із цією родиною.
     *
     * @return процесор оплати
     */
    PaymentProcessor createPaymentProcessor();

    /**
     * Створює службу доставки, сумісну із цією родиною.
     *
     * @return служба доставки
     */
    ShippingProvider createShippingProvider();
}
